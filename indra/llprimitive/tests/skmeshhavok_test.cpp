    // Same hash the fixture generator computes over the oracle's constraint list.
    U64 chain_hash(const SKMoppTree& tree, S32 last, U32& count)
    {
        std::vector<const SKMoppConstraint*> path;
        for (S32 c = last; c >= 0; c = tree.mConstraints[c].mParent)
        {
            path.push_back(&tree.mConstraints[c]);
        }
        std::reverse(path.begin(), path.end());
        count = (U32)path.size();
        U64 h = 0xCBF29CE484222325ULL;
        for (const SKMoppConstraint* c : path)
        {
            const SKMoppFrame& frame = tree.mFrames[c->mFrame];
            const S64 values[] = { c->mOpcode, c->mKind, c->mLo, c->mHi, (S64)frame.mFactor,
                                   (S64)std::llround(frame.mOffset[0] * 65536.0),
                                   (S64)std::llround(frame.mOffset[1] * 65536.0),
                                   (S64)std::llround(frame.mOffset[2] * 65536.0) };
            for (S64 v : values)
            {
                for (S32 b = 0; b < 8; ++b)
                {
                    h ^= (U8)((U64)v >> (8 * b));
                    h *= 0x100000001B3ULL;
                }
            }
        }
        return h;
    }

    std::string deflate_bytes(const std::string& raw)
    {
        uLongf size = compressBound((uLong)raw.size());
        std::string out(size, '\0');
        compress(reinterpret_cast<Bytef*>(&out[0]), &size, reinterpret_cast<const Bytef*>(raw.data()), (uLong)raw.size());
        out.resize(size);
        return out;
    }

